-- Cleanup. Temp tables are session-scoped and would vanish with the psql
-- session regardless; dropped explicitly so a long-lived operator session
-- (or a re-run within the same session) starts clean.
-- ===========================================================================
DROP TABLE IF EXISTS tf_format_qualified_2116;
DROP TABLE IF EXISTS format_qualifier_map_2116;
